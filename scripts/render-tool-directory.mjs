/**
 * Write the MCP tool directory into public/index.html as static HTML, so
 * crawlers that do not run scripts still see every tool name, description
 * and parameter. The browser refreshes the same block from /api/tools.
 *
 *   node scripts/render-tool-directory.mjs          rewrite index.html
 *   node scripts/render-tool-directory.mjs --check  exit 1 if it is stale
 */
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {vehicleTools} from '../lib/mcp/vehicle-tools.mjs';
import {researchTools} from '../lib/mcp/research-tools.mjs';
import {accountTools} from '../lib/mcp/account-tools.mjs';

const START = '<!-- tool-directory:start (generated by scripts/render-tool-directory.mjs) -->';
const END = '<!-- tool-directory:end -->';
const page = new URL('../public/index.html', import.meta.url);
const esc = text => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Same grouping and order as lib/mcp/index.mjs, without opening the database. */
export function toolGroups() {
  const groups = [];
  const collect = name => {
    const tools = []; groups.push({name, tools});
    return (tool, description, inputSchema) => tools.push({name: tool, description, params: Object.keys(inputSchema || {})});
  };
  vehicleTools(collect('Vehicle reports'));
  researchTools(collect('Research and analysis'));
  accountTools(collect('Saved vehicles and preferences'), {});
  return groups;
}

export function renderToolDirectory(groups = toolGroups()) {
  return groups.map(group => [
    `<section class="tool-group"><h4>${esc(group.name)} · ${group.tools.length} tools</h4><div class="tool-list">`,
    ...group.tools.map(tool => {
      const params = tool.params.length ? ` <span class="tool-params">(${tool.params.map(esc).join(', ')})</span>` : '';
      return `<div class="tool-entry"><code>${esc(tool.name)}</code>${params}<p>${esc(tool.description)}</p></div>`;
    }),
    '</div></section>',
  ].join('\n')).join('\n');
}

export async function currentPage() {
  const html = await readFile(page, 'utf8');
  const from = html.indexOf(START), to = html.indexOf(END);
  if (from < 0 || to < from) throw new Error('tool-directory markers are missing from public/index.html');
  return {html, from: from + START.length, to};
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const {html, from, to} = await currentPage();
  const updated = html.slice(0, from) + '\n' + renderToolDirectory() + '\n' + html.slice(to);
  if (process.argv.includes('--check')) {
    if (updated !== html) { console.error('public/index.html tool directory is stale: run node scripts/render-tool-directory.mjs'); process.exit(1); }
  } else if (updated !== html) await writeFile(page, updated);
}
