#!/usr/bin/env node
/**
 * The difference between mcp.vin's vPIC rule tables and NHTSA's, as a readable Markdown file: every reviewed rule fix
 * (data-src/vpic-rule-fixes.jsonl) with NHTSA's original rule row, our edit, the decode errors it fixes, the reason and
 * the NHTSA lab reports behind it, and whether it applied to the release in data/vpic.db. It doubles as the error
 * report we can send NHTSA.
 *
 * Usage: node scripts/vpic-rule-diff.mjs [--db data/vpic.db] [--out docs/vpic-rule-fixes.md]
 * Reads only the built file (rule_fix_entry records every entry of the changeset, applied or not).
 */
import Database from 'better-sqlite3';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };
const DB = arg('--db', fileURLToPath(new URL('../data/vpic.db', import.meta.url)));
const OUT = arg('--out', null);

// Rows we noticed while tracing the fixes that look wrong too but are not in the reviewed list (not changed).
const NOTICED = [
  {table: 'pattern', id: 810115, note: 'The 2007 Sentra pattern AB61 names the VQ35DE (3.5 L V6) engine; the car has a 2.0 L four (fixed rows rf-012 give it 4 cylinders and 2.0 L). The engine-model row was not in the reviewed list, so it is left as NHTSA has it.'},
];

const db = new Database(DB, {readonly: true, fileMustExist: true});
const meta = Object.fromEntries(db.prepare('SELECT key, value FROM meta').all().map(r => [r.key, r.value]));
const hasFixTables = !!db.prepare("SELECT 1 FROM sqlite_master WHERE name = 'rule_fix_entry'").get();
if (!hasFixTables) { console.error(`${DB} was built without rule fixes (scripts/import-vpic.py --no-rule-fixes or an older build).`); process.exit(2); }
const entries = db.prepare('SELECT * FROM rule_fix_entry ORDER BY fix_id').all().map(e => ({...e, edits: JSON.parse(e.edits), errors: JSON.parse(e.errors), evidence: JSON.parse(e.evidence),
  reviewed: JSON.parse(e.reviewed), premise: e.premise ? JSON.parse(e.premise) : []}));
const el = new Map(db.prepare('SELECT id, code, value_table FROM element').all().map(e => [e.code, e]));
const lookupName = (code, attr) => {
  const e = el.get(code);
  if (!e?.value_table) return attr;
  return db.prepare('SELECT name FROM lookup WHERE tbl = ? AND id = ?').get(e.value_table, String(attr))?.name ?? attr;
};
const md = s => String(s ?? '').replace(/\|/g, '\\|');
const CASES = {
  wrong_value: 'wrong value: the row covers the right VINs and states the wrong value',
  narrower_key: 'narrower key: the VIN positions separate the versions; the row is narrowed or a narrower row is added',
  wrong_row: 'wrong row: a row overrides NHTSA\'s own more specific rows; it is removed',
  missing_rule: 'missing rule: NHTSA describes the engine but no row states the field; a row is added on NHTSA\'s own keys',
};

function rowText(ed) {
  if (ed.table === 'spec_pattern') return `vehicle-spec row ${ed.row.id} (${md(ed.row.applies_to)})`;
  const r = ed.row || ed.new;
  return `${ed.action === 'add' ? 'new row' : `row ${r.id}`} in schema ${r.schema_id} "${md(r.schema)}", keys \`${md(r.keys)}\``;
}
function editText(ed) {
  const r = ed.row;
  if (ed.action === 'delete') return `**removed** (${md(r.element)} = ${md(r.value)})`;
  if (ed.action === 'add') return `**added**: ${md(ed.new.element)} = ${md(ed.new.value)}`;
  const parts = [];
  if (ed.set.keys !== undefined && ed.set.keys !== r.keys) parts.push(`keys \`${md(r.keys)}\` → \`${md(ed.set.keys)}\``);
  if (ed.set.attribute_id !== undefined && String(ed.set.attribute_id) !== String(r.attribute_id)) parts.push(`${md(r.element)} ${md(r.value)} → **${md(ed.set.value)}**`);
  else parts.push(`${md(r.element)} = ${md(r.value)} (unchanged)`);
  return parts.join('; ');
}

const lines = [];
const applied = entries.filter(e => e.status === 'applied'), review = entries.filter(e => e.status !== 'applied');
lines.push('# mcp.vin fixes to NHTSA\'s vPIC decoding rules', '');
lines.push(`Generated by \`scripts/vpic-rule-diff.mjs\` from \`data/vpic.db\` (NHTSA vPIC release **${meta.release}**, built ${meta.built_at}). Do not edit by hand.`, '');
lines.push('NHTSA\'s vPIC decoder turns a VIN into vehicle attributes with rule tables: each `pattern` row says that VINs of a WMI and model-year range whose characters match `keys` (VIN positions 4-8, then `|` and positions 10-17; `*` any character, `[...]` a set) have a value for one element (drive type, cylinders, ...). Vehicle-spec rows add values for a make, model and year from already decoded values (for example every "Launch Model" trim).', '');
lines.push('mcp.vin decodes VINs with NHTSA\'s own algorithm over NHTSA\'s monthly database, with the rule edits below applied at build time (`data-src/vpic-rule-fixes.jsonl`, `scripts/import-vpic.py`). Each edit names the exact NHTSA row it changes; when a new release changes that row, the edit is not applied and is reported for review. Every value a fix changes is shown with NHTSA\'s official value beside it.', '');
lines.push('The errors were found by comparing vPIC\'s decode of NHTSA\'s own crash-test and compliance-test vehicles with NHTSA\'s lab record of each vehicle (decode audit 2026-11-17), checked against EPA\'s configuration list; the evidence links are NHTSA\'s lab reports.', '');
lines.push(`**${entries.length}** fixes (${applied.length} applied, ${review.length} need review), **${applied.reduce((n, e) => n + e.edits.length, 0)}** row edits, correcting **${entries.reduce((n, e) => n + e.errors.length, 0)}** decode errors.`, '');
const byCase = {};
for (const e of entries) byCase[e.fix_case] = (byCase[e.fix_case] || 0) + 1;
lines.push('| Kind of fix | Fixes |', '|---|---|');
for (const [k, n] of Object.entries(byCase).sort((a, b) => b[1] - a[1])) lines.push(`| ${md(CASES[k] || k)} | ${n} |`);
lines.push('');
lines.push('## Summary', '', '| Fix | Vehicle | Field | NHTSA decodes | Correct | Status |', '|---|---|---|---|---|---|');
for (const e of entries) {
  for (const x of e.errors) lines.push(`| [${e.fix_id}](#${e.fix_id}) | ${x.model_year} ${md(x.make)} ${md(x.model)} (\`${md(x.pattern)}\`) | ${md(x.field)} | ${md(x.vpic_value)} | ${md(x.correct_value)} | ${e.status === 'applied' ? 'applied' : '**needs review**'} |`);
}
lines.push('');
for (const e of entries) {
  const first = e.errors[0];
  const vehicles = [...new Set(e.errors.map(x => `${x.model_year} ${x.make} ${x.model}`))].join(', ');
  lines.push(`## ${e.fix_id}`, '', `**${md(vehicles)}**: ${md([...new Set(e.errors.map(x => x.field))].join(', '))}. ${md(CASES[e.fix_case] || e.fix_case)}. Written against release ${e.written_against}; ${e.status === 'applied' ? `applied to ${meta.release}` : `**not applied to ${meta.release}: ${md(e.problem)}**`}.`, '');
  lines.push('| NHTSA rule row | Edit |', '|---|---|');
  for (const ed of e.edits) lines.push(`| ${rowText(ed)} | ${editText(ed)} |`);
  for (const p of e.premise) lines.push(`| ${rowText(p)} | unchanged: ${md(p.row.element)} = ${md(p.row.value)} (NHTSA's row the fix relies on; it must be unchanged for the fix to apply) |`);
  lines.push('');
  lines.push('VIN patterns it corrects (positions 1-8, check digit `*`, positions 10-11):', '');
  for (const x of e.errors) lines.push(`- \`${md(x.pattern)}\` ${md(x.field)}: NHTSA decodes "${md(x.vpic_value)}", correct "${md(x.correct_value)}" (${x.test_vehicles} NHTSA test vehicle${x.test_vehicles === 1 ? '' : 's'})`);
  lines.push('', md(e.reason), '');
  const ev = e.evidence.map(v => `[${v.test_no ? `test ${v.test_no}` : 'report'}](${v.url})`).join(', ');
  if (ev) lines.push(`NHTSA lab reports: ${ev}.`, '');
  void first;
}
lines.push('## Noticed, not changed', '');
for (const n of NOTICED) {
  const r = db.prepare('SELECT p.*, s.name AS schema FROM pattern p JOIN vinschema s ON s.id = p.schema_id WHERE p.id = ?').get(n.id);
  if (!r) { lines.push(`- ${n.table} row ${n.id}: no longer in release ${meta.release}.`); continue; }
  const code = [...el.values()].find(e => e.id === r.element_id)?.code;
  lines.push(`- Row ${r.id} in schema ${r.schema_id} "${md(String(r.schema).trim())}", keys \`${md(r.keys)}\`: ${md(code)} = ${md(lookupName(code, r.attribute_id))}. ${md(n.note)}`);
}
lines.push('');
const text = lines.join('\n');
if (OUT) { writeFileSync(OUT, text); console.log(`wrote ${OUT} (${entries.length} fixes)`); } else process.stdout.write(text);
